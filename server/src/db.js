import pg from 'pg';

const { Pool, types } = pg;

// Keep timestamp fields serialized as strings, as they were in the SQLite API.
types.setTypeParser(1114, value => value);

const connectionString = process.env.DATABASE_URL;
if (!connectionString) {
  throw new Error('DATABASE_URL is required to connect to PostgreSQL.');
}

const postgresUrl = new URL(connectionString);
// SSL is configured explicitly below so URL sslmode options cannot override it.
for (const option of ['sslmode', 'sslcert', 'sslkey', 'sslrootcert']) postgresUrl.searchParams.delete(option);

export const pool = new Pool({
  connectionString: postgresUrl.toString(),
  // Neon requires TLS. DATABASE_URL stays in the environment, never in source.
  ssl: { rejectUnauthorized: true },
  max: Number(process.env.PG_POOL_MAX || 10),
  idleTimeoutMillis: 30_000,
  connectionTimeoutMillis: 10_000,
});

pool.on('error', error => {
  console.error('Unexpected idle PostgreSQL client error:', error.message);
});

