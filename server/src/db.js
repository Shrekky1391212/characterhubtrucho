import pg from 'pg';

const { Pool, types } = pg;

// Keep timestamp fields serialized as strings, as they were in the SQLite API.
types.setTypeParser(1114, value => value);

const connectionString = process.env.DATABASE_URL;
if (!connectionString) {
  throw new Error('DATABASE_URL is required to connect to PostgreSQL.');
}

const postgresUrl = new URL(connectionString);
// SSL is configured explicitly below so URL sslmode options cannot override it.
for (const option of ['sslmode', 'sslcert', 'sslkey', 'sslrootcert']) postgresUrl.searchParams.delete(option);

export const pool = new Pool({
  connectionString: postgresUrl.toString(),
  // Neon requires TLS. DATABASE_URL stays in the environment, never in source.
  ssl: { rejectUnauthorized: true },
  max: Number(process.env.PG_POOL_MAX || 10),
  idleTimeoutMillis: 30_000,
  connectionTimeoutMillis: 10_000,
});

pool.on('error', error => {
  console.error('Unexpected idle PostgreSQL client error:', error.message);
});

const schemaStatements = [
  `CREATE TABLE IF NOT EXISTS universes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    genre TEXT NOT NULL DEFAULT '',
    tone TEXT NOT NULL DEFAULT '',
    color TEXT NOT NULL DEFAULT '#c2a878',
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
  )`,
  `CREATE TABLE IF NOT EXISTS characters (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    universe_id INTEGER REFERENCES universes(id) ON DELETE SET NULL,
    name TEXT NOT NULL,
    alias TEXT NOT NULL DEFAULT '',
    pronouns TEXT NOT NULL DEFAULT '',
    gender TEXT NOT NULL DEFAULT '',
    species TEXT NOT NULL DEFAULT '',
    origin TEXT NOT NULL DEFAULT '',
    residence TEXT NOT NULL DEFAULT '',
    occupation TEXT NOT NULL DEFAULT '',
    status TEXT NOT NULL DEFAULT '',
    powers TEXT NOT NULL DEFAULT '',
    tags TEXT NOT NULL DEFAULT '',
    description TEXT NOT NULL DEFAULT '',
    biography TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
  )`,
  `CREATE TABLE IF NOT EXISTS universe_themes (
    universe_id INTEGER PRIMARY KEY REFERENCES universes(id) ON DELETE CASCADE,
    prompt TEXT NOT NULL DEFAULT '',
    page_bg TEXT NOT NULL DEFAULT '#f7f6f2',
    panel_bg TEXT NOT NULL DEFAULT '#fffefa',
    ink TEXT NOT NULL DEFAULT '#282720',
    muted TEXT NOT NULL DEFAULT '#8c8980',
    line TEXT NOT NULL DEFAULT '#e9e7df',
    accent TEXT NOT NULL DEFAULT '#9b845c',
    sidebar_bg TEXT NOT NULL DEFAULT '#24231f',
    heading_font TEXT NOT NULL DEFAULT 'serif',
    texture TEXT NOT NULL DEFAULT 'plain',
    corner TEXT NOT NULL DEFAULT 'soft',
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
  )`,
  'CREATE INDEX IF NOT EXISTS idx_characters_universe ON characters(universe_id)',
  'CREATE INDEX IF NOT EXISTS idx_characters_name ON characters(LOWER(name))',
];

export async function initializeDatabase() {
  const client = await pool.connect();
  try {
    await client.query('SELECT 1');
    await client.query('BEGIN');
    for (const statement of schemaStatements) await client.query(statement);
    await client.query('COMMIT');
  } catch (error) {
    await client.query('ROLLBACK').catch(() => {});
    throw error;
  } finally {
    client.release();
  }
}
