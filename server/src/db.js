// Inspect legacy rows before adding the Phase 1 foreign keys/triggers. This is
// intentionally read-only: incompatible rows are reported and left untouched.
async function preflightLegacyRelations(client) {
  const checks = [
    ['characters', `SELECT c.id, c.owner_id, c.universe_id, c.universe_node_id,
       u.owner_id AS universe_owner_id, n.universe_id AS node_universe_id, n.owner_id AS node_owner_id
     FROM characters c
     LEFT JOIN universes u ON u.id=c.universe_id
     LEFT JOIN universe_nodes n ON n.id=c.universe_node_id
     WHERE (c.universe_id IS NOT NULL AND u.id IS NULL)
        OR (c.universe_id IS NOT NULL AND u.owner_id IS DISTINCT FROM c.owner_id)
        OR (c.universe_node_id IS NOT NULL AND (n.id IS NULL OR n.owner_id IS DISTINCT FROM c.owner_id OR n.universe_id IS DISTINCT FROM c.universe_id))`],
    ['archive_entries', `SELECT e.id, e.owner_id, e.universe_id, e.universe_node_id,
       u.owner_id AS universe_owner_id, n.universe_id AS node_universe_id, n.owner_id AS node_owner_id
     FROM archive_entries e
     LEFT JOIN universes u ON u.id=e.universe_id
     LEFT JOIN universe_nodes n ON n.id=e.universe_node_id
     WHERE (e.universe_id IS NOT NULL AND u.id IS NULL)
        OR (e.universe_id IS NOT NULL AND u.owner_id IS DISTINCT FROM e.owner_id)
        OR (e.universe_node_id IS NOT NULL AND (n.id IS NULL OR n.owner_id IS DISTINCT FROM e.owner_id OR n.universe_id IS DISTINCT FROM e.universe_id))`],
    ['archive_entries', `SELECT e.id, e.parent_id, e.universe_id, e.scope_kind,
       p.universe_id AS parent_universe_id, p.scope_kind AS parent_scope_kind
     FROM archive_entries e JOIN archive_entries p ON p.id=e.parent_id
     WHERE e.owner_id IS DISTINCT FROM p.owner_id OR (e.scope_kind, e.universe_id) IS DISTINCT FROM (p.scope_kind, p.universe_id)`],
    ['character_relationships', `SELECT r.id, r.source_character_id, r.target_character_id,
       s.scope_kind AS source_scope, s.universe_id AS source_universe_id,
       t.scope_kind AS target_scope, t.universe_id AS target_universe_id
     FROM character_relationships r
     JOIN characters s ON s.id=r.source_character_id
     JOIN characters t ON t.id=r.target_character_id
     WHERE s.owner_id IS DISTINCT FROM r.owner_id OR t.owner_id IS DISTINCT FROM r.owner_id
        OR (s.scope_kind, s.universe_id) IS DISTINCT FROM (t.scope_kind, t.universe_id)`],
    ['entry_links', `SELECT l.id, l.source_entry_id, l.target_entry_id, l.target_character_id,
       s.scope_kind AS source_scope, s.universe_id AS source_universe_id,
       COALESCE(t.scope_kind,c.scope_kind) AS target_scope,
       COALESCE(t.universe_id,c.universe_id) AS target_universe_id
     FROM entry_links l
     JOIN archive_entries s ON s.id=l.source_entry_id
     LEFT JOIN archive_entries t ON t.id=l.target_entry_id
     LEFT JOIN characters c ON c.id=l.target_character_id
     WHERE s.owner_id IS DISTINCT FROM l.owner_id
        OR (l.target_entry_id IS NOT NULL AND (t.owner_id IS DISTINCT FROM l.owner_id OR (s.scope_kind,s.universe_id) IS DISTINCT FROM (t.scope_kind,t.universe_id)))
        OR (l.target_character_id IS NOT NULL AND (c.owner_id IS DISTINCT FROM l.owner_id OR (s.scope_kind,s.universe_id) IS DISTINCT FROM (c.scope_kind,c.universe_id)))`],
  ];
  const conflicts = [];
  for (const [table, sql] of checks) {
    const exists = await client.query('SELECT to_regclass($1) IS NOT NULL AS present', [`public.${table}`]);
    if (!exists.rows[0].present) continue;
    const result = await client.query(sql);
    for (const row of result.rows) conflicts.push({ table, ...row });
  }
  if (conflicts.length) {
    const report = formatMigrationConflictReport(conflicts);
    const error = new Error(`Migración detenida: se encontraron ${conflicts.length} relaciones históricas entre ámbitos/universos distintos. No se modificaron ni borraron esos registros. Corrigilos manualmente y volvé a iniciar:\n${report}`);
    error.code = 'LEGACY_RELATION_CONFLICTS';
    error.conflicts = conflicts;
    throw error;
  }
}

export async function initializeDatabase(targetPool = pool) {
  const client = await targetPool.connect();
  try {
    await client.query('SELECT 1');
    await client.query('BEGIN');
    for (const statement of schemaStatements) {
      // Scope columns have now been added/backfilled, while the composite
      // universe constraints have not yet been installed.
      if (statement.includes("conname = 'archive_entries_universe_owner_fk'")) {
        await preflightLegacyRelations(client);
        await client.query(`DO $$ BEGIN
          IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'characters_universe_owner_fk') THEN
            ALTER TABLE characters ADD CONSTRAINT characters_universe_owner_fk
              FOREIGN KEY(owner_id, universe_id) REFERENCES universes(owner_id, id) ON DELETE CASCADE;
          END IF;
        END $$`);
        await client.query(`DO $$ BEGIN
          IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'characters_node_universe_fk') THEN
            ALTER TABLE characters ADD CONSTRAINT characters_node_universe_fk
              FOREIGN KEY(owner_id, universe_id, universe_node_id) REFERENCES universe_nodes(owner_id, universe_id, id) ON DELETE SET NULL (universe_node_id);
          END IF;
        END $$`);
      }
      await client.query(statement);
    }
    await client.query('COMMIT');
  } catch (error) {
    await client.query('ROLLBACK').catch(() => {});
    throw error;
  } finally {
    client.release();
  }
}
