const { Pool, types } = pg;

// Keep timestamp fields serialized as strings, as they were in the SQLite API.
types.setTypeParser(1114, value => value);

let productionPool;
function getProductionPool() {
  if (productionPool) return productionPool;
  const connectionString = process.env.DATABASE_URL;
  if (!connectionString) throw new Error('DATABASE_URL is required to connect to PostgreSQL.');
  const postgresUrl = new URL(connectionString);
  // SSL is configured explicitly below so URL sslmode options cannot override it.
  for (const option of ['sslmode', 'sslcert', 'sslkey', 'sslrootcert']) postgresUrl.searchParams.delete(option);
  productionPool = new Pool({
    connectionString: postgresUrl.toString(),
    // Neon requires TLS. DATABASE_URL stays in the environment, never in source.
    ssl: { rejectUnauthorized: true },
    max: Number(process.env.PG_POOL_MAX || 10),
    idleTimeoutMillis: 30_000,
    connectionTimeoutMillis: 10_000,
  });
  productionPool.on('error', error => console.error('Unexpected idle PostgreSQL client error:', error.message));
  return productionPool;
}

// Importing the app for an isolated test must not create a network pool.
// Production still gets the same pg.Pool on its first database operation.
export const pool = new Proxy(Object.create(null), {
  get(_target, property) {
    const target = getProductionPool();
    const value = target[property];
    return typeof value === 'function' ? value.bind(target) : value;
  },
});

