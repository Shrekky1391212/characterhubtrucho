export async function applyPhase2SchemaForIsolatedTest(client) {
  if (process.env.DATABASE_URL || process.env.TEST_DATABASE_URL) {
    throw new Error('Refusing Phase 2 DDL while a database URL is configured; this schema helper is restricted to an ephemeral in-memory test instance.');
  }
  const identity = await client.query('SELECT version() AS version, inet_server_addr() AS address');
  if (!/PGlite/i.test(identity.rows[0]?.version || '') || identity.rows[0]?.address !== null) {
    throw new Error('Refusing Phase 2 DDL: the connection is not a verified in-memory PGlite instance.');
  }
  const report = await inspectLegacyData(client);
  if (!report.safeToBackfill) {
    const error = new Error(`Phase 2 schema preparation stopped by preinspection: ${report.conflicts.map(row => `${row.code} (${row.total})`).join(', ')}`);
    error.code = 'PHASE2_PREFLIGHT_FAILED';
    error.report = report;
    throw error;
  }
  await client.query('BEGIN');
  try {
    for (const statement of phase2Statements) await client.query(statement);
    await client.query('COMMIT');
  } catch (error) {
    await client.query('ROLLBACK').catch(() => {});
    throw error;
  }
}

