export async function inspectLegacyData(client) {
  const conflicts = [];
  for (const [code, sql] of legacyChecks) {
    const table = code.includes('character') ? (code === 'invalid_character_relationships' ? 'character_relationships' : 'characters')
      : code.includes('entry') && code !== 'cyclic_universe_nodes' ? (code === 'invalid_entry_links' ? 'entry_links' : 'archive_entries')
        : 'universe_nodes';
    const exists = await client.query('SELECT to_regclass($1) IS NOT NULL AS present', [`public.${table}`]);
    if (!exists.rows[0].present) continue;
    const result = await client.query(`SELECT *, count(*) OVER()::int AS total_count FROM (${sql}) q LIMIT 100`);
    if (result.rows.length) {
      const total = result.rows[0].total_count;
      conflicts.push({ code, total, sample: result.rows.map(({ total_count, ...row }) => row), truncated: total > result.rows.length });
    }
  }
  const collisions = await client.query(`SELECT c.id, c.owner_id AS character_owner_id, e.owner_id AS entry_owner_id
    FROM characters c JOIN archive_entries e ON e.id=c.id ORDER BY c.id LIMIT 100`)
    .catch(() => ({ rows: [] }));
  const tagRows = await client.query(`SELECT id,tags FROM characters WHERE tags LIKE '%,%' ORDER BY id LIMIT 100`).catch(() => ({ rows: [] }));
  const tagCount = tagRows.rows.length ? await client.query("SELECT count(*)::int AS count FROM characters WHERE tags LIKE '%,%'").catch(() => ({ rows: [{ count: tagRows.rows.length }] })) : { rows: [{ count: 0 }] };
  return {
    safeToBackfill: conflicts.length === 0,
    conflicts,
    informational: [
      ...(collisions.rows.length ? [{ code: 'overlapping_legacy_numeric_ids', meaning: 'Expected across separate tables; source_kind must be part of the registry key.', sample: collisions.rows }] : []),
      ...(tagRows.rows.length ? [{ code: 'comma_delimited_character_tags', meaning: 'Review splitting only on commas during backfill; original characters.tags remains untouched.', total: tagCount.rows[0].count, sample: tagRows.rows }] : []),
    ],
  };
}
