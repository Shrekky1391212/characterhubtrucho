import test from 'node:test';
import assert from 'node:assert/strict';
import express from 'express';
import { PGlite } from '@electric-sql/pglite';
import { applyPhase2SchemaForIsolatedTest } from '../src/phase2-schema.js';
import { createPhase2Router } from '../src/phase2-router.js';

async function fixture({ phase2 = true } = {}) {
  assert.equal(process.env.DATABASE_URL, undefined, 'DATABASE_URL must be absent before creating a fixture');
  assert.equal(process.env.TEST_DATABASE_URL, undefined, 'TEST_DATABASE_URL must be absent before creating a fixture');
  const db = new PGlite('memory://');
  const identity = await db.query('SELECT version() AS version, inet_server_addr() AS address');
  assert.match(identity.rows[0].version, /PGlite/);
  assert.equal(identity.rows[0].address, null);
  await db.exec(`
    CREATE TABLE users(id INTEGER PRIMARY KEY);
    CREATE TABLE universes(id INTEGER PRIMARY KEY,owner_id INTEGER NOT NULL,name TEXT NOT NULL,UNIQUE(owner_id,id));
    CREATE TABLE universe_nodes(id INTEGER PRIMARY KEY,owner_id INTEGER NOT NULL,universe_id INTEGER NOT NULL,parent_id INTEGER,name TEXT NOT NULL,node_type TEXT NOT NULL DEFAULT 'section',description TEXT NOT NULL DEFAULT '',sort_order INTEGER NOT NULL DEFAULT 0);
    CREATE TABLE characters(id INTEGER PRIMARY KEY,owner_id INTEGER NOT NULL,scope_kind TEXT NOT NULL,universe_id INTEGER,universe_node_id INTEGER,name TEXT NOT NULL,description TEXT NOT NULL DEFAULT '',tags TEXT NOT NULL DEFAULT '',details JSONB NOT NULL DEFAULT '{}'::jsonb);
    CREATE TABLE archive_entries(id INTEGER PRIMARY KEY,owner_id INTEGER NOT NULL,scope_kind TEXT NOT NULL,universe_id INTEGER,universe_node_id INTEGER,parent_id INTEGER,kind TEXT NOT NULL,name TEXT NOT NULL,description TEXT NOT NULL DEFAULT '',tags TEXT[] NOT NULL DEFAULT '{}',data JSONB NOT NULL DEFAULT '{}'::jsonb);
    CREATE TABLE content_types(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,owner_id INTEGER NOT NULL,slug TEXT NOT NULL,label TEXT NOT NULL,icon TEXT NOT NULL DEFAULT 'archive',UNIQUE(owner_id,slug));
    CREATE TABLE universe_themes(universe_id INTEGER PRIMARY KEY,owner_id INTEGER NOT NULL,prompt TEXT NOT NULL DEFAULT '');
    CREATE TABLE entry_links(id INTEGER PRIMARY KEY,owner_id INTEGER NOT NULL,source_entry_id INTEGER NOT NULL,target_entry_id INTEGER,target_character_id INTEGER);
    CREATE TABLE character_relationships(id INTEGER PRIMARY KEY,owner_id INTEGER NOT NULL,source_character_id INTEGER NOT NULL,target_character_id INTEGER NOT NULL);
  `);
  if (phase2) await applyPhase2SchemaForIsolatedTest(db);
  const pool = {
    query: (...args) => db.query(...args),
    connect: async () => ({
      query: (...args) => {
        const [sql] = args;
        if (failureSql && String(sql).includes(failureSql)) { failureSql = null; throw new Error('synthetic transaction failure'); }
        return db.query(...args);
      },
      release() {},
    }),
  };
  let failureSql = null;
  const app = express();
  app.use(express.json());
  // Production mounts this router after the existing session authenticator.
  // The fixture injects an owner identity without inventing a new auth system.
  app.use((req, _res, next) => { req.user = { id: Number(req.get('x-test-owner')) }; next(); });
  app.use('/api/v2', createPhase2Router(pool));
  const server = await new Promise(resolve => {
    const listening = app.listen(0, '127.0.0.1', () => resolve(listening));
  });
  const base = `http://127.0.0.1:${server.address().port}/api/v2`;
  return {
    db,
    failNextClientQuery(fragment) { failureSql = fragment; },
    async request(owner, path, { method = 'GET', body } = {}) {
      const response = await fetch(base + path, {
        method,
        headers: { 'x-test-owner': String(owner), ...(body ? { 'content-type': 'application/json' } : {}) },
        ...(body ? { body: JSON.stringify(body) } : {}),
      });
      const data = response.status === 204 ? null : await response.json();
      return { status: response.status, data };
    },
    async close() {
      await new Promise((resolve, reject) => server.close(error => error ? reject(error) : resolve()));
      await db.close();
    },
  };
}

async function seed(db) {
  await db.query('INSERT INTO users(id) VALUES(1),(2)');
  await db.query("INSERT INTO universes(id,owner_id,name) VALUES(10,1,'A'),(11,1,'A2'),(20,2,'B')");
  await db.query("INSERT INTO content_types(id,owner_id,slug,label) VALUES(100,1,'relic','Relic'),(200,2,'secret','Secret')");
  await db.query("INSERT INTO universe_themes(universe_id,owner_id,prompt) VALUES(10,1,'preserve this theme')");
}

