test('content identity is owner-scoped and disambiguates matching legacy IDs', async () => {
  const f = await fixture();
  try {
    await seed(f.db);
    await f.db.query("INSERT INTO characters(id,owner_id,scope_kind,universe_id,name,tags) VALUES(7,1,'universe',10,'Character seven','one, two')");
    await f.db.query("INSERT INTO archive_entries(id,owner_id,scope_kind,universe_id,kind,name) VALUES(7,1,'universe',10,'location','Location seven')");
    const characters = await f.request(1, '/content-items/source/characters/7');
    const entries = await f.request(1, '/content-items/source/archive_entries/7');
    const list = await f.request(1, '/content-items');
    const foreign = await f.request(2, '/content-items/source/characters/7');
    assert.equal(characters.data.source_type, 'character');
    assert.equal(entries.data.source_type, 'location');
    assert.equal(characters.data.source_table, 'characters');
    assert.equal(entries.data.source_table, 'archive_entries');
    assert.equal(characters.data.migrated, true, 'legacy inserts after v2 activation are mirrored transactionally');
    assert.equal(entries.data.migrated, true, 'legacy inserts after v2 activation are mirrored transactionally');
    assert.deepEqual(list.data.map(item => item.source_table).sort(), ['archive_entries', 'characters']);
    assert.equal(foreign.status, 404);
  } finally { await f.close(); }
});

test('groups support mixed memberships, scoped groups, and preserve items when memberships change', async () => {
  const f = await fixture();
  try {
    await seed(f.db);
    await f.db.query(`INSERT INTO content_items(id,owner_id,type_key,scope_kind,universe_id,name) VALUES
      (1,1,'character','universe',10,'A'),(2,1,'location','universe',11,'A2'),
      (3,1,'note','global',NULL,'Global'),(4,1,'event','pending',NULL,'Pending')`);
    const account = await f.request(1, '/groups', { method: 'POST', body: { name: 'Mixed', tags: ['archive'], sort_order: 4 } });
    const account2 = await f.request(1, '/groups', { method: 'POST', body: { name: 'Second' } });
    const universe = await f.request(1, '/groups', { method: 'POST', body: { name: 'A only', universe_id: 10 } });
    assert.equal(account.status, 201);
    assert.equal(universe.data.space_type, 'universe');
    for (const itemId of [1, 2, 3, 4]) assert.equal((await f.request(1, `/groups/${account.data.id}/items`, { method: 'POST', body: { item_id: itemId } })).status, 201);
    assert.equal((await f.request(1, `/groups/${account2.data.id}/items`, { method: 'POST', body: { item_id: 1 } })).status, 201);
    const incompatible = await f.request(1, `/groups/${universe.data.id}/items`, { method: 'POST', body: { item_id: 2 } });
    assert.equal(incompatible.status, 409);
    const items = await f.request(1, `/groups/${account.data.id}/items`);
    assert.equal(items.data.length, 4);
    const removed = await f.request(1, `/groups/${account.data.id}/items/1`, { method: 'DELETE' });
    assert.equal(removed.status, 204);
    assert.equal((await f.db.query('SELECT count(*)::int AS n FROM content_items WHERE id=1 AND owner_id=1')).rows[0].n, 1);
    assert.equal((await f.db.query('SELECT count(*)::int AS n FROM content_group_items WHERE owner_id=1 AND item_id=1')).rows[0].n, 1);
    const theme = await f.db.query('SELECT prompt FROM universe_themes WHERE universe_id=10 AND owner_id=1');
    assert.equal(theme.rows[0].prompt, 'preserve this theme');
  } finally { await f.close(); }
});

test('subgroups inherit spaces, cycles and incompatible moves roll back, and delete retains content', async () => {
  const f = await fixture();
  try {
    await seed(f.db);
    await f.db.query("INSERT INTO content_items(id,owner_id,type_key,scope_kind,universe_id,name) VALUES(1,1,'character','universe',10,'A'),(2,1,'note','global',NULL,'G')");
    const root = await f.request(1, '/groups', { method: 'POST', body: { name: 'Root', universe_id: 10 } });
    const child = await f.request(1, '/groups', { method: 'POST', body: { name: 'Child', parent_group_id: root.data.id } });
    assert.equal(child.data.universe_id, 10);
    assert.equal(child.data.space_type, 'universe');
    assert.equal((await f.request(1, `/groups/${child.data.id}`, { method: 'PATCH', body: { name: 'Child renamed', description: 'D', color: '#123456', image_url: 'https://example.test/cover.png', tags: ['x'], sort_order: 7 } })).status, 200);
    assert.equal((await f.request(1, `/groups/${child.data.id}/move`, { method: 'PATCH', body: { parent_group_id: child.data.id } })).status, 400);
    const cycle = await f.request(1, `/groups/${root.data.id}/move`, { method: 'PATCH', body: { parent_group_id: child.data.id } });
    assert.equal(cycle.status, 409);
    const reordered = await f.request(1, `/groups/${root.data.id}/reorder`, { method: 'PATCH', body: { sort_order: 12 } });
    assert.equal(reordered.status, 200);
    assert.equal(reordered.data.sort_order, 12);
    const scoped = await f.request(1, '/groups', { method: 'POST', body: { name: 'Account group' } });
    await f.request(1, `/groups/${scoped.data.id}/items`, { method: 'POST', body: { item_id: 2 } });
    const moveConflict = await f.request(1, `/groups/${scoped.data.id}/move`, { method: 'PATCH', body: { parent_group_id: null, space_type: 'universe', universe_id: 10 } });
    assert.equal(moveConflict.status, 409);
    const afterConflict = await f.request(1, `/groups/${scoped.data.id}`);
    assert.equal(afterConflict.data.space_type, 'account');
    assert.equal((await f.request(1, `/groups/${root.data.id}`, { method: 'DELETE' })).status, 409);
    assert.equal((await f.request(1, `/groups/${child.data.id}/move`, { method: 'PATCH', body: { parent_group_id: null, space_type: 'account', universe_id: null } })).status, 200);
    assert.equal((await f.request(1, `/groups/${child.data.id}`, { method: 'DELETE' })).status, 204);
    assert.equal((await f.db.query('SELECT count(*)::int AS n FROM content_items WHERE id=1')).rows[0].n, 1);
  } finally { await f.close(); }
});

test('arbitrarily deep subgroups work and multi-statement type creation rolls back atomically', async () => {
  const f = await fixture();
  try {
    await seed(f.db);
    let parent = null;
    for (let depth = 0; depth < 9; depth++) {
      const created = await f.request(1, '/groups', { method: 'POST', body: { name: `Level ${depth}`, ...(parent ? { parent_group_id: parent.id } : { universe_id: 10 }) } });
      assert.equal(created.status, 201);
      if (parent) assert.equal(created.data.universe_id, 10);
      parent = created.data;
    }
    const before = (await f.db.query("SELECT count(*)::int AS n FROM content_groups WHERE owner_id=1")).rows[0].n;
    assert.equal(before, 9);

    f.failNextClientQuery('INSERT INTO content_type_configs');
    const failed = await f.request(1, '/content-types', { method: 'POST', body: { label: 'Must Roll Back', field_schema: [] } });
    assert.equal(failed.status, 500);
    const partial = await f.db.query("SELECT count(*)::int AS n FROM content_types WHERE owner_id=1 AND slug='must-roll-back'");
    assert.equal(partial.rows[0].n, 0, 'the type insert is rolled back when its configuration insert fails');
  } finally { await f.close(); }
});

