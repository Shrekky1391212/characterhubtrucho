test('types validate configuration, preserve omitted fields, reorder, retire, and protect in-use types', async () => {
  const f = await fixture();
  try {
    await seed(f.db);
    const bad = await f.request(1, '/content-types', { method: 'POST', body: { label: 'Relic', field_schema: [{ key: 'x', label: 'Choice', type: 'select' }] } });
    assert.equal(bad.status, 400);
    const created = await f.request(1, '/content-types', { method: 'POST', body: { label: 'Artifact', icon: 'gem', field_schema: [{ key: 'rarity', label: 'Rarity', type: 'text' }] } });
    assert.equal(created.status, 201);
    const type = await f.db.query('SELECT id FROM content_types WHERE owner_id=1 AND slug=$1', ['artifact']);
    const typeId = type.rows[0].id;
    await f.db.query("INSERT INTO content_items(owner_id,type_key,content_type_id,scope_kind,name,data) VALUES(1,'custom',$1,'global','Keeps values','{\"rarity\":\"rare\"}')", [typeId]);
    assert.equal((await f.request(1, `/content-types/${typeId}`, { method: 'PATCH', body: { label: 'Relics' } })).status, 200);
    const config = await f.db.query('SELECT field_schema FROM content_type_configs WHERE content_type_id=$1', [typeId]);
    assert.deepEqual(config.rows[0].field_schema, [{ key: 'rarity', label: 'Rarity', type: 'text' }]);
    const values = await f.db.query('SELECT data FROM content_items WHERE content_type_id=$1', [typeId]);
    assert.deepEqual(values.rows[0].data, { rarity: 'rare' }, 'editing type metadata does not rewrite element values');
    assert.equal((await f.request(1, '/content-types/reorder', { method: 'PATCH', body: { ids: [typeId, 100] } })).status, 200);
    assert.equal((await f.request(1, `/content-types/${typeId}/retire`, { method: 'POST' })).status, 200);
    assert.equal((await f.request(1, '/content-types/100/retire', { method: 'POST' })).status, 200, 'existing types without a sidecar config can be retired');
    assert.equal((await f.db.query('SELECT is_active FROM content_type_configs WHERE content_type_id=100')).rows[0].is_active, false);
    assert.equal((await f.request(1, '/content-types/100', { method: 'DELETE' })).status, 204, 'unused type can be physically removed');
    await f.db.query("INSERT INTO content_items(owner_id,type_key,content_type_id,scope_kind,name) VALUES(1,'custom',$1,'pending','Used')", [typeId]);
    const inUse = await f.request(1, `/content-types/${typeId}`, { method: 'DELETE' });
    assert.equal(inUse.status, 409);
    assert.equal((await f.request(2, `/content-types/${typeId}`, { method: 'PATCH', body: { label: 'Stolen' } })).status, 404);
    assert.equal((await f.request(1, '/content-types/200', { method: 'DELETE' })).status, 404);
  } finally { await f.close(); }
});
